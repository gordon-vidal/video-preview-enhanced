'use strict';
// node tools/build-ui.js [--check]: bundles media/ui/index.ts (Preact, @preact/signals, @floating-ui/dom) into
// media/dist/webview-ui.js, a browser IIFE that sets globalThis.VpeWebviewUi (ADR 0004). The bundle is committed so
// the VSIX needs no build step or node_modules; --check fails when the committed file differs from a fresh build.
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const root = path.join(__dirname, '..');
const entry = path.join(root, 'media', 'ui', 'index.ts');
const out = path.join(root, 'media', 'dist', 'webview-ui.js');
const rel = path.relative(root, out).split(path.sep).join('/');

const BANNER = '/* Generated by tools/build-ui.js from media/ui/ (npm run build:ui). Do not edit. Licences: THIRD_PARTY_NOTICES.md */';

async function build() {
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'VpeWebviewUi',
    platform: 'browser',
    // .tsx components use Preact's automatic JSX runtime (tsconfig.ui.json says the same for the type check).
    jsx: 'automatic',
    jsxImportSource: 'preact',
    // VS Code 1.82 ships Chromium 114.
    target: 'chrome114',
    minify: true,
    legalComments: 'none',
    banner: { js: BANNER },
    // Same bytes on every machine: no absolute paths or timestamps in the output.
    logLevel: 'silent',
  });
  const text = result.outputFiles[0].text.replace(/\r\n/g, '\n');
  return text;
}

async function main() {
  const text = await build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current !== text) {
      process.stderr.write(`${rel} is ${current === null ? 'missing' : 'out of date'}: run npm run build:ui\n`);
      process.exitCode = 1;
      return;
    }
    console.log(`${rel} is up to date`);
    return;
  }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`Wrote ${rel} (${text.length} bytes)`);
}

main().catch((err) => {
  process.stderr.write(`${err && err.message ? err.message : err}\n`);
  process.exitCode = 1;
});
