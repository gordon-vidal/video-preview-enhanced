#!/usr/bin/env node
'use strict';
// Recomputes the time limits of layers 1-3 from the recorded runs and writes them as explicit numbers
// (docs/TESTING.md, "Time limits"):
//
//   node test/tune_timeouts.js [--history <a test/ folder holding out/ and vscode/out/>] [--dry]
//
//   layers 1-2   test/out/{unit,engine}-*.json (per-file ms of every passed run):
//                timeout = max(20 s, 4 x median, 2 x slowest passed run), up to the next 5 s
//                stall   = max(30 s, 3 x longest silent gap of a passed run) when runs recorded gaps
//                -> the block between the "timeouts:" markers in test/layers.js
//   layer 3      test/vscode/out/scenarios-*.json plus the typical times in the table of
//                test/vscode/README.md: budget = max(90 s, 2.5 x median + 30 s), 3.5 x for scenarios
//                with native / remote / URL / HDR / many-video work -> test/vscode/budgets.js
//
// Failed and timed-out runs are not history. Re-run it after a layer got slower or faster on purpose.
const fs = require('fs');
const path = require('path');

const argv = process.argv.slice(2);
const opt = (n, d) => { const i = argv.indexOf(n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };
const HIST = path.resolve(opt('--history', __dirname));
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s.length ? (s.length % 2 ? s[s.length >> 1] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : null; };
const up5 = (ms) => Math.ceil(ms / 5000) * 5000;
const readJson = (f) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return null; } };
const list = (dir, re) => { try { return fs.readdirSync(dir).filter((f) => re.test(f)).sort().map((f) => path.join(dir, f)); } catch { return []; } };
const obj = (o, q) => `{\n${Object.entries(o).map(([k, v]) => `  ${q || /\W/.test(k) ? `'${k}'` : k}: ${v},`).join('\n')}\n}`;

// ---- layers 1-2 ----
const times = {}; const gaps = {};
for (const f of list(path.join(HIST, 'out'), /^(unit|engine)-.*\.json$/)) {
  const j = readJson(f);
  for (const r of (j && j.results) || []) {
    if (!r.ok || r.skipped || !r.ms) continue;
    (times[r.file] = times[r.file] || []).push(r.ms);
    if (r.gapMs) (gaps[r.file] = gaps[r.file] || []).push(r.gapMs);
  }
}
const TIMEOUTS = {}; const STALLS = {};
for (const file of Object.keys(times).sort()) {
  TIMEOUTS[file] = up5(Math.max(20000, 4 * median(times[file]), 2 * Math.max(...times[file])));
  if (gaps[file]) STALLS[file] = Math.min(TIMEOUTS[file], up5(Math.max(30000, 3 * Math.max(...gaps[file]))));
}
const lf = path.join(__dirname, 'layers.js');
let src = fs.readFileSync(lf, 'utf8');
const block = `// timeouts: generated by test/tune_timeouts.js from test/out/*.json (explicit numbers, ms; edit by hand if you must)\nconst TIMEOUTS = ${obj(TIMEOUTS, true)};\nconst STALLS = ${obj(STALLS, true)}; // longest allowed silence per file; default 30 s\n// :timeouts`;
if (!/\/\/ timeouts:[\s\S]*?\/\/ :timeouts/.test(src)) throw new Error('test/layers.js has no "// timeouts:" ... "// :timeouts" block');
src = src.replace(/\/\/ timeouts:[\s\S]*?\/\/ :timeouts/, () => block);

// ---- layer 3 ----
const typical = {};
const readme = fs.readFileSync(path.join(__dirname, 'vscode', 'README.md'), 'utf8');
for (const m of readme.matchAll(/^\| `([\w-]+)` \|.*\| (\d+) s, \d+ \|\s*$/gm)) typical[m[1]] = [Number(m[2]) * 1000];
for (const f of list(path.join(HIST, 'vscode', 'out'), /^scenarios-.*\.json$/)) {
  const j = readJson(f);
  for (const s of (j && j.scenarios) || []) if (!s.failed && s.ms) (typical[s.name] = typical[s.name] || []).push(s.ms);
}
const SLOW = /native|remote|url|hdr|large|invisible|restore|multiview/;
const BUDGETS = {};
for (const name of Object.keys(typical).sort()) BUDGETS[name] = up5(Math.max(90000, (SLOW.test(name) ? 3.5 : 2.5) * median(typical[name]) + 30000));
const bsrc = `'use strict';\n// Time budget per layer-3 scenario in ms (test/vscode/scenarios.js): past it the scenario is ended and reported as\n// TIMEOUT with the step it was in. Generated by test/tune_timeouts.js (2.5 x typical + 30 s, min 90 s; 3.5 x for\n// native / remote / URL / HDR / many-video scenarios). A scenario not listed gets DEFAULT.\nconst BUDGETS = ${obj(BUDGETS)};\nmodule.exports = { BUDGETS, DEFAULT: 600000 };\n`;

if (argv.includes('--dry')) console.log(block, '\n', bsrc);
else {
  fs.writeFileSync(lf, src);
  fs.writeFileSync(path.join(__dirname, 'vscode', 'budgets.js'), bsrc);
  console.log(`wrote ${Object.keys(TIMEOUTS).length} file timeouts (${Object.keys(STALLS).length} stalls) to test/layers.js, ${Object.keys(BUDGETS).length} scenario budgets to test/vscode/budgets.js`);
}
